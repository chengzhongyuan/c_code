// 函数重载 函数名相同，参数列表不同
// 参数列表不同：参数个数不同，参数类型不同，参数顺序不同
// 单单返回值不同，无法构成重载
void show(int a)
{
    cout<<"show(int a)"<<endl;
}
void show(double a)
{
    cout<<"show(double a)"<<endl;
}
void show(int a, int b)
{
    cout<<"show(int a, int b)"<<endl;
}

// extern "C" void func1() 当希望c，c++程序都可以找到(动静态库)
// 作用：告诉编译器按照C语言的方式去编译func1函数，
// 避免C++的名称修饰，从而使得该函数可以被C语言调用
extern "C" void func1()
{
    cout<<"func1"<<endl;
}

// 引用的概念
// 引用是C++的一种数据类型，它是某个变量的别名。共用一块空间
// 引用在定义时必须初始化，且一旦初始化后不能改变引用的对象。
void test01()
{
    int a = 10;
    int &b = a; // b是a的引用
    cout<<a<<endl; // 10
    cout<<b<<endl; // 10
    b = 20; // 通过引用修改了a的值
    cout<<a<<endl; // 20
    cout<<b<<endl; // 20
    // 隐式类型转换
    //int &c; // 错误，引用必须初始化
    //int &d = 10; // 错误，引用必须是一个变量
    const double &e = 10; // 正确，常量引用可以引用一个临时变量
    
    // double &e = a; 
    const double &e = 10;
    cout<<e<<endl; // 10

    // 查看地址
    cout<<&a<<endl; // 0x7ffee4b2c8cc
    cout<<&b<<endl; // 0x7ffee4b2c8cc
}

