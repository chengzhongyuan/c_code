// 重载：面试问题
// 1、什么是函数重载
// 函数重载是指在同一个作用域中，允许存在多个同名但参数列表不同的函数。
// 编译器根据函数调用时传递的参数类型和数量来决定调用哪个具体的函数版本。
// 2、函数重载的条件
// 参数个数不同，参数类型不同，参数顺序不同
// 3、c++是怎么完成函数重载的，问什么c不行
// c++编译器在编译阶段会对函数名进行“名称修饰”（Name Mangling），
// 将函数名与其参数类型和数量结合起来生成一个唯一的标识符，从而实现函数重载。
// 而C语言没有名称修饰机制，因此不支持函数重载。
// 4、函数重载的优点和缺点  
// 优点：提高代码的可读性和可维护性，使得函数名更具描述性，便于理解函数的用途。
// 缺点：可能导致编译器在解析函数调用时产生歧义

