from openpyxl import Workbook

# 课程数据
courses = [
    ["公共必修", "英语学术文献阅读", "100011C6", 32, 2, "2024-2025第一学期", 83, "李蓓"],
    ["公共必修", "自然辩证法概论", "140001C6", 18, 1, "2024-2025第二学期", 81, "程慧敏"],
    ["公共必修", "新时代中国特色社会主义理论与实践研究", "140005C6", 36, 2, "2024-2025第二学期", 60, "王慧"],
    ["专业必修", "学科前沿讲座（硕博贯通）", "060001S6", 32, 2, "2024-2025第一学期", 84, "王雪松"],
    ["专业必修", "智能优化与控制（硕博贯通）", "060062S6", 32, 2, "2024-2025第一学期", 83, "张勇"],
    ["专业必修", "大数据分析理论与技术（硕博贯通）", "060065S6", 32, 2, "2024-2025第一学期", 81, "俞昆"],
    ["专业必修", "非线性控制理论及应用（硕博贯通）", "060066S6", 32, 2, "2024-2025第一学期", 73, "叶宾"],
    ["专业必修", "高等工程数学", "080014B6", 32, 2, "2024-2025第一学期", 70, "张杰"],
    ["专业必修", "现代检测技术及应用", "060009S6", 32, 2, "2024-2025第二学期", 79, "吴新忠"]
]

# 创建 Excel 工作簿
wb = Workbook()
ws = wb.active
ws.title = "成绩表"

# 写入表头
headers = ["课程性质", "课程名称", "课程代码", "学时", "学分", "学期", "成绩", "任课教师", "成绩×学分"]
ws.append(headers)

# 写入课程数据并计算加权成绩
total_score = 0
total_credit = 0

for course in courses:
    credit = course[4]
    score = course[6]
    weighted = credit * score
    total_score += weighted
    total_credit += credit
    ws.append(course + [weighted])

# 写入加权平均成绩
ws.append([])
ws.append(["加权平均成绩", round(total_score / total_credit, 2)])

# 保存 Excel 文件
wb.save("成绩表.xlsx")
print(f"✅ Excel 文件已生成，加权平均成绩为：{round(total_score / total_credit, 2)}")
